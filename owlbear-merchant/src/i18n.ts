const TABLES: Record<Lang, Record<string, string>> = {
  "pt-BR": pt as Record<string, string>,
  en: en as Record<string, string>,
};

export const LANGS: { id: Lang; label: string }[] = [
  { id: "pt-BR", label: "Português" },
  { id: "en", label: "English" },
];

export function t(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let value = TABLES[lang][key] ?? TABLES.en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export const RARITY_KEYS: RarityKey[] = [
  "common",
  "uncommon",
  "rare",
  "veryRare",
  "legendary",
  "artifact",
];

export function rarityLabel(lang: Lang, key: RarityKey | ""): string {
  if (!key) return t(lang, "rarity.none");
  return t(lang, `rarity.${key}`);
}
